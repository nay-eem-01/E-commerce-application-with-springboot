package com.ecommerce.notification.service;

import com.ecommerce.common.event.OrderNotificationEvent;
import com.ecommerce.common.event.OrderNotificationEvent.OrderSummary;
import com.ecommerce.notification.config.MailProperties;
import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Component;
import org.springframework.web.util.HtmlUtils;

import java.math.BigDecimal;
import java.math.RoundingMode;
import java.text.NumberFormat;
import java.util.Locale;

/**
 * Renders each order email as plain text and HTML. Every value that came from a shopper or the
 * catalog is HTML-escaped; links are built only from the configured storefront URL and the
 * order number (which is generated by us), never from input.
 */
@Component
@RequiredArgsConstructor
public class EmailTemplates {

	private final MailProperties properties;

	public record Rendered(String subject, String text, String html) {}

	public Rendered render(OrderNotificationEvent event) {
		OrderSummary o = event.order();
		String brand = properties.brandName();
		String trackUrl = properties.storefrontUrl() + "/track?order=" + o.orderNumber();
		String orderUrl = properties.storefrontUrl() + "/orders/" + o.orderNumber();
		String hello = "Hi " + firstName(o.customerName()) + ",";

		return switch (event.type()) {
			case PLACED -> {
				String pay = o.onlinePayment()
						? "We will email you as soon as your " + label(o.paymentMethod()) + " payment is confirmed."
						: "Please have " + money(o.total()) + " ready. You can check the parcel before you pay the rider.";
				yield build("Order " + o.orderNumber() + " received - " + brand, hello,
						"Thank you for your order. Here is what you bought:", o, true,
						pay + "\nDelivery to " + o.district() + ": " + o.deliveryEstimate() + ".",
						"Track your order", trackUrl);
			}
			case PAYMENT_RECEIVED -> build("Payment received for order " + o.orderNumber(), hello,
					"We received your " + label(o.paymentMethod()) + " payment of " + money(o.total()) + ". We are packing your order now.",
					o, false, "Delivery to " + o.district() + ": " + o.deliveryEstimate() + ".", "Track your order", trackUrl);
			case SHIPPED -> build("Order " + o.orderNumber() + " is on its way", hello,
					"Your order is with the rider. They will call you before arriving.", o, false,
					o.onlinePayment() ? "It is already paid." : "Please have " + money(o.total()) + " ready for the rider.",
					"Track your order", trackUrl);
			case DELIVERED -> build("Order " + o.orderNumber() + " delivered", hello,
					"Your order was delivered. We hope you love it!", o, false,
					"Unopened items can be returned within 7 days. If something arrived damaged, reply with a photo.",
					"Review what you bought", orderUrl);
			case CANCELLED -> build("Order " + o.orderNumber() + " cancelled", hello,
					"Your order was cancelled" + (event.note() == null ? "." : ": " + event.note() + "."), o, false,
					o.onlinePayment() ? "If you paid online, the money goes back to the same account within a few working days."
							: "Nothing was charged.",
					"Shop again", properties.storefrontUrl());
		};
	}

	/** The copy staff get for every new order. */
	public Rendered staffCopy(OrderSummary o) {
		return build("New order " + o.orderNumber() + " - " + money(o.total()), "New order,",
				o.customerName() + " ordered for delivery to " + o.district() + " (" + label(o.paymentMethod()) + "):",
				o, true, "Open the admin orders page to pack it.", null, null);
	}

	private Rendered build(String subject, String hello, String intro, OrderSummary o, boolean itemsWithTotals,
						   String outro, String linkLabel, String linkUrl) {
		StringBuilder text = new StringBuilder();
		StringBuilder rows = new StringBuilder();
		text.append(hello).append("\n\n").append(intro).append("\n\nOrder ").append(o.orderNumber()).append("\n");
		for (OrderNotificationEvent.Line l : o.lines()) {
			String name = l.name() + (l.optionLabel() == null ? "" : " (" + l.optionLabel() + ")");
			text.append("- ").append(l.quantity()).append(" x ").append(name).append("  ").append(money(l.lineTotal())).append("\n");
			rows.append("<tr><td style=\"padding:6px 0\">").append(l.quantity()).append(" &times; ").append(esc(name))
					.append("</td><td style=\"padding:6px 0;text-align:right;white-space:nowrap\">").append(esc(money(l.lineTotal()))).append("</td></tr>");
		}
		if (itemsWithTotals) {
			text.append("\nSubtotal: ").append(money(o.subtotal()))
					.append("\nDelivery: ").append(o.deliveryFee().signum() == 0 ? "Free" : money(o.deliveryFee()))
					.append("\nTotal: ").append(money(o.total())).append("\n");
			rows.append(totalRow("Subtotal", money(o.subtotal()), false))
					.append(totalRow("Delivery", o.deliveryFee().signum() == 0 ? "Free" : money(o.deliveryFee()), false))
					.append(totalRow("Total", money(o.total()), true));
		}
		text.append("\n").append(outro).append("\n");
		if (linkUrl != null) {
			text.append("\n").append(linkLabel).append(": ").append(linkUrl).append("\n");
		}
		text.append("\n").append(properties.brandName()).append("\n");

		String html = """
				<!doctype html><html><body style="margin:0;background:#f4f2f7;font-family:Arial,Helvetica,sans-serif;color:#1c1830">
				<table role="presentation" width="100%%" cellpadding="0" cellspacing="0"><tr><td align="center" style="padding:24px 12px">
				<table role="presentation" width="560" cellpadding="0" cellspacing="0" style="max-width:560px;background:#ffffff;border-radius:8px">
				<tr><td style="padding:20px 24px;background:#1c1830;color:#ffffff;border-radius:8px 8px 0 0;font-size:20px;font-weight:bold">%s</td></tr>
				<tr><td style="padding:24px;font-size:15px;line-height:1.6">
				<p style="margin:0 0 12px">%s</p><p style="margin:0 0 16px">%s</p>
				<p style="margin:0 0 8px;font-weight:bold">Order %s</p>
				<table role="presentation" width="100%%" cellpadding="0" cellspacing="0" style="border-top:1px solid #e3dfeb">%s</table>
				<p style="margin:16px 0">%s</p>%s
				</td></tr></table></td></tr></table></body></html>
				""".formatted(esc(properties.brandName()), esc(hello), esc(intro), esc(o.orderNumber()), rows,
				esc(outro).replace("\n", "<br>"),
				linkUrl == null ? "" : "<p style=\"margin:20px 0 0\"><a href=\"" + esc(linkUrl)
						+ "\" style=\"display:inline-block;background:#d63384;color:#ffffff;padding:12px 20px;border-radius:4px;text-decoration:none;font-weight:bold\">"
						+ esc(linkLabel) + "</a></p>");
		return new Rendered(subject, text.toString(), html);
	}

	private static String totalRow(String label, String value, boolean strong) {
		String w = strong ? "font-weight:bold;" : "";
		return "<tr><td style=\"padding:6px 0;border-top:1px solid #e3dfeb;" + w + "\">" + label
				+ "</td><td style=\"padding:6px 0;border-top:1px solid #e3dfeb;text-align:right;" + w + "\">" + esc(value) + "</td></tr>";
	}

	static String money(BigDecimal amount) {
		NumberFormat f = NumberFormat.getNumberInstance(Locale.US);
		f.setMaximumFractionDigits(amount.stripTrailingZeros().scale() > 0 ? 2 : 0);
		f.setMinimumFractionDigits(amount.stripTrailingZeros().scale() > 0 ? 2 : 0);
		return "\u09F3 " + f.format(amount.setScale(2, RoundingMode.HALF_UP));
	}

	private static String label(String method) {
		return switch (method) {
			case "BKASH" -> "bKash";
			case "NAGAD" -> "Nagad";
			case "CARD" -> "card";
			default -> "cash on delivery";
		};
	}

	private static String firstName(String name) {
		return name == null || name.isBlank() ? "there" : name.trim().split("\\s+")[0];
	}

	private static String esc(String s) {
		return s == null ? "" : HtmlUtils.htmlEscape(s);
	}
}
